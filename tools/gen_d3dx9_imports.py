#!/usr/bin/env python3
"""Generate a D3DX import table from pinned Wine headers.

The JSON names the DLL, the table symbol and each export's handler. The stdcall
argument count is read from the declaration so a hand-written mismatch cannot
persist. Missing or ambiguous declarations fail rather than guessing.
--check verifies committed output without modifying it.
"""
import argparse
import json
from pathlib import Path
import re

from gen_com_interfaces import preprocess


def declaration_arity(text, name):
    start = re.search(r'\bWINAPI\s+' + re.escape(name) + r'\s*\(', text)
    if start is None:
        raise ValueError('missing declaration: ' + name)
    if re.search(r'\bWINAPI\s+' + re.escape(name) + r'\s*\(', text[start.end():]):
        raise ValueError('ambiguous declaration: ' + name)
    index, depth = start.end(), 1
    while index < len(text) and depth:
        depth += text[index] == '('
        depth -= text[index] == ')'
        index += 1
    if depth:
        raise ValueError('unterminated declaration: ' + name)
    arguments = text[start.end():index - 1]
    if not arguments.strip():
        return 0
    depth, commas = 0, 0
    for char in arguments:
        depth += char == '('
        depth -= char == ')'
        commas += char == ',' and depth == 0
    return commas + 1


def render(references, spec, sdk_version):
    text = preprocess('\n'.join(reference.decode('utf-8') for reference in references), sdk_version)
    dll, table = spec['dll'], spec['table']
    if not re.fullmatch(r'[A-Za-z0-9_.]+', dll):
        raise ValueError('invalid DLL name: ' + dll)
    names = [entry['name'] for entry in spec['imports']]
    if len(set(names)) != len(names):
        raise ValueError('duplicate import name')
    for entry in spec['imports']:
        if not re.fullmatch(r'[A-Za-z_]\w*', entry['name']):
            raise ValueError('invalid import name: ' + entry['name'])
        if not re.fullmatch(r'[A-Za-z_]\w*', entry['handler']):
            raise ValueError('invalid handler: ' + entry['handler'])
    lines = ['// Generated by tools/gen_d3dx9_imports.py; do not edit.', '']
    lines.append('static const ImportShim ' + table + '[] = {')
    for entry in sorted(spec['imports'], key=lambda item: item['name']):
        argc = declaration_arity(text, entry['name'])
        lines.append(f'    {{"{dll}", "{entry["name"]}", {argc}, {entry["handler"]}}},')
    lines.extend(['};', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, nargs='+', required=True)
    parser.add_argument('--imports', type=Path, required=True)
    parser.add_argument('--sdk-version', type=int, default=33)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        spec = json.loads(args.imports.read_text())
        if not re.fullmatch(r'[A-Za-z_]\w*', spec['table']):
            raise ValueError('invalid table symbol: ' + spec['table'])
        generated = render([path.read_bytes() for path in args.reference], spec, args.sdk_version)
        if args.check:
            if args.output.read_text() != generated:
                parser.error(str(args.output) + ' is stale; regenerate D3DX imports')
        elif not args.output.exists() or args.output.read_text() != generated:
            args.output.write_text(generated)
    except (ValueError, OSError, KeyError) as failure:
        parser.error(str(failure))


if __name__ == '__main__':
    main()
